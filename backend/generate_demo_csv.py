"""
Deterministic generator for `web/public/demo-sales.csv`.
Illustrative synthetic demo data — not real retailer records.
"""

from __future__ import annotations

import csv
import datetime as dt
import math
from pathlib import Path
import random

SEED = 20261026
DAYS = 120
END_DATE = dt.date(2026, 10, 26)
START_DATE = END_DATE - dt.timedelta(days=DAYS - 1)  # 2026-06-29 .. 2026-10-26


def generate_rows() -> list[tuple[str, str, str, int]]:
    rng = random.Random(SEED)
    rows: list[tuple[str, str, str, int]] = []

    skus = [
        ("rice-1kg", "Miniket Rice 1kg (Synthetic Demo)"),
        ("soap-100g", "Neem Bath Soap 100g (Synthetic Demo)"),
        ("tea-250g", "Sylhet Black Tea 250g (Synthetic Demo)"),
    ]

    for pid, pname in skus:
        for day_idx in range(DAYS):
            current_date = START_DATE + dt.timedelta(days=day_idx)
            weekday = current_date.weekday()  # 0=Mon .. 6=Sun

            if pid == "rice-1kg":
                # Staple item with strong Thursday/Friday/Saturday retail demand + gentle positive trend
                weekday_boost = {0: 0, 1: 1, 2: 2, 3: 6, 4: 10, 5: 8, 6: -2}[weekday]
                trend = 0.05 * day_idx
                base = 16.0 + weekday_boost + trend + rng.gauss(0.0, 1.8)
                # Explicit zero-sales days on specific seeded intervals (e.g., occasional stockout/closed day)
                if day_idx in {19, 61}:
                    qty = 0
                else:
                    qty = max(0, int(round(base)))

            elif pid == "soap-100g":
                # Moderate personal care item with weekly rhythm + explicit 0-sales days
                weekday_effect = {0: -2, 1: 0, 2: 1, 3: 3, 4: 5, 5: 4, 6: -3}[weekday]
                wave = 2.0 * math.sin(2.0 * math.pi * day_idx / 14.0)
                base = 6.0 + weekday_effect + wave + rng.gauss(0.0, 1.4)
                if day_idx in {6, 27, 55, 83, 104}:
                    qty = 0
                else:
                    qty = max(0, int(round(base)))

            else:  # tea-250g
                # Steady beverage staple with mid-week and weekend peaks + gentle trend
                weekday_effect = {0: 2, 1: 3, 2: 4, 3: 2, 4: 6, 5: 5, 6: -1}[weekday]
                trend = 0.03 * day_idx
                base = 9.0 + weekday_effect + trend + rng.gauss(0.0, 1.2)
                if day_idx in {13, 48, 90}:
                    qty = 0
                else:
                    qty = max(0, int(round(base)))

            rows.append((current_date.isoformat(), pid, pname, qty))

    return rows


def main() -> None:
    repo_root = Path(__file__).resolve().parent.parent
    public_dir = repo_root / "web" / "public"
    public_dir.mkdir(parents=True, exist_ok=True)

    csv_path = public_dir / "demo-sales.csv"
    rows = generate_rows()

    with csv_path.open("w", encoding="utf-8", newline="\n") as f:
        writer = csv.writer(f, lineterminator="\n")
        writer.writerow(["date", "product_id", "product_name", "quantity_sold"])
        writer.writerows(rows)

    readme_path = public_dir / "demo-sales-README.md"
    readme_path.write_text(
        "# Illustrative Synthetic Demo Data — Not Real Retailer Records\n\n"
        "- **File**: `demo-sales.csv`\n"
        "- **Provenance**: Deterministically generated by `backend/generate_demo_csv.py` (seed `20261026`).\n"
        "- **Disclaimer**: **Illustrative synthetic demo data — not real retailer records.** "
        "Contains 3 synthetic SKUs (`rice-1kg`, `soap-100g`, `tea-250g`) across 120 consecutive calendar days "
        "(`2026-06-29` through `2026-10-26`, 360 rows total), including explicit `0` rows on zero-sales days.\n"
        "- **Pipeline**: Loaded in the browser and sent as `multipart/form-data` to `POST /backend/v1/analyze` "
        "through the exact same server validation and forecasting pipeline as user-uploaded CSV files.\n",
        encoding="utf-8",
    )
    print(f"Wrote {len(rows)} rows to {csv_path}")


if __name__ == "__main__":
    main()
